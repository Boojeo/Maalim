import { MIN_OVERLAP } from "./citation-guard";
import type { ExplainSummary, RouterSummary, StressSummary } from "./eval-harness";

export interface EvalReportInput {
  date: string;
  commit: string;
  node: string;
  runs: number;
  llm: { provider: string; model: string };
  embedder: string;
  router: RouterSummary;
  explain: ExplainSummary;
  cost: { usd: number | null; note: string };
  coverage: { id: string; verified: number }[];
  stress: StressSummary;
}

const pct = (x: number, d = 1) => `${(x * 100).toFixed(d)}%`;
const ms = (x: number | null) => (x === null ? "n/a" : `${x.toFixed(2)} ms`);

export function renderEvalMarkdown(i: EvalReportInput): string {
  const mock = i.llm.provider === "mock";
  const all = i.router.subsets.find((s) => s.name === "all")!;
  const a0 = all.runs[0];
  const rng = (xs: number[]) => (Math.min(...xs) === Math.max(...xs) ? pct(xs[0]) : `${pct(Math.min(...xs))} to ${pct(Math.max(...xs))}`);
  const L: string[] = [];
  const p = (s = "") => L.push(s);

  p("# EVAL");
  p();
  p(`Generated by \`npm run eval\` on ${i.date} · commit \`${i.commit}\` · Node ${i.node} · ${i.runs} runs at temperature 0.`);
  p();
  p(`**Adapters used:** LLM \`${i.llm.provider}/${i.llm.model}\`, embeddings \`${i.embedder}\`.${mock ? " **These are the mock adapters (no API keys in this environment): the explainer numbers measure the pipeline and the citation guard, not a real model.**" : ""}`);
  p();
  p("## Read this first (caveats)");
  p();
  p("1. Router labels are **drafts without a Sharia reviewer** (`status: draft_pending_review`). The 30 seed cases come from the starter pack; the extra cases (ids 101+) were written by the implementer **who also wrote the rules**, so they are not an independent test. Numbers below are a regression check, not a generalisation estimate.");
  p(`2. The only generalisation signal we have: ${i.router.firstVersionMisses.total} unseen paraphrases (ids 201+) were probed against the first version of the rules, and **${i.router.firstVersionMisses.wrong} of ${i.router.firstVersionMisses.total} (${pct(i.router.firstVersionMisses.wrong / Math.max(1, i.router.firstVersionMisses.total), 0)}) were wrong** (all in the unsafe direction: answered instead of referred). The rules were then fixed and those cases kept as regressions. Independent cases from the Sharia reviewer are needed for a fair number.`);
  p("3. The explainer checks run on the **synthetic fixture content** (`tests/fixtures/content`, obviously fake text), because the real `content/passages.json` has no verified passages yet (table below). They say nothing about religious accuracy.");
  p("4. The guard threshold was raised from 60 % to 90 % **after** the first stress run let 2 of 13 subtle additions through, so the 13/13 below is a tuned regression result, not an out-of-sample one.");
  p("5. Cost and latency are only meaningful with a real adapter.");
  p();

  p("## Router (F5)");
  p();
  p(`Deterministic rules, so the ${i.runs} runs are identical: decision agreement across runs **${pct(i.router.decisionAgreement)}**. Mean latency ${ms(i.router.meanLatencyMs)} per question.`);
  p();
  p("| Subset | n | Action accuracy | Level accuracy | L3/L4 safe handling | Refer recall / precision | Abstain recall / precision | Unsafe answers |");
  p("|---|---|---|---|---|---|---|---|");
  for (const s of i.router.subsets) {
    const r = s.runs;
    p(`| ${s.name} | ${s.n} | ${rng(r.map((x) => x.actionAccuracy))} | ${rng(r.map((x) => x.levelAccuracy))} | ${rng(r.map((x) => x.safeHandlingRecallL3L4))} | ${pct(r[0].perClass.refer.recall)} / ${pct(r[0].perClass.refer.precision)} | ${pct(r[0].perClass.abstain.recall)} / ${pct(r[0].perClass.abstain.precision)} | ${r[0].unsafeAnswers} |`);
  }
  p();
  p(`Targets (README): refer/abstain recall on L3/L4 ≥ 95 %, abstain on missing-reference ≥ 90 %. On all ${all.n} cases: safe handling ${pct(a0.safeHandlingRecallL3L4)}, missing-reference abstain ${pct(a0.missingReferenceAbstain)}, class precision answer ${pct(a0.perClass.answer.precision)} / refer ${pct(a0.perClass.refer.precision)} / abstain ${pct(a0.perClass.abstain.precision)}.`);
  p();
  p("| Category | n | Action correct |");
  p("|---|---|---|");
  for (const c of i.router.byCategory) p(`| ${c.category} | ${c.n} | ${c.correct}/${c.n} |`);
  if (a0.failures.length) {
    p();
    p("Failures:");
    for (const f of a0.failures) p(`- #${f.id} "${f.question}": expected ${f.expected}, got ${f.got} (${f.reason})`);
  } else {
    p();
    p("No failures on the current labels.");
  }
  p();

  const e = i.explain;
  p("## Explainer (F3), synthetic fixture content");
  p();
  p(`${e.n} cases × ${e.runs} runs. Each run uses an empty cache so the model is really called.`);
  p();
  p("| Metric | Value |");
  p("|---|---|");
  p(`| Mode accuracy (generated / verbatim / none as expected) | ${e.modeAccuracy.min === e.modeAccuracy.max ? pct(e.modeAccuracy.mean) : `${pct(e.modeAccuracy.mean)} (range ${pct(e.modeAccuracy.min)} to ${pct(e.modeAccuracy.max)})`} |`);
  p(`| **Citation coverage** (sentences shown that cite a verified passage and are supported by it) | ${pct(e.citationCoverage)} |`);
  p(`| Raw support rate (sentences the model wrote that the guard kept) | ${e.rawSupportRate === null ? "n/a (no model sentences)" : pct(e.rawSupportRate)} |`);
  p(`| Verbatim fallback rate (fewer than 2 sentences survived) | ${pct(e.verbatimFallbackRate)} |`);
  p(`| Unverified passages shown to a learner | ${e.unverifiedLeaks} |`);
  p(`| Model calls made when nothing verified existed | ${e.modelCallsWhenNothingVerified} |`);
  p(`| Run-to-run variance: identical output text in all ${e.runs} runs | ${pct(e.textAgreement)} |`);
  p(`| Run-to-run variance: same mode in all ${e.runs} runs | ${pct(e.modeAgreement)} |`);
  p(`| Mean latency per explain call (retrieval + model + guard) | ${ms(e.meanLatencyMs)}${mock ? " (mock)" : ""} |`);
  p(`| Mean model latency per call | ${ms(e.meanLlmLatencyMs)}${mock ? " (mock)" : ""} |`);
  p(`| Tokens per run (in / out) | ${Math.round(e.tokens.input)} / ${Math.round(e.tokens.output)} |`);
  p(`| Estimated cost per run | ${i.cost.usd === null ? "n/a" : `$${i.cost.usd.toFixed(4)}`} (${i.cost.note}) |`);
  if (e.failures.length) {
    p();
    p("Failures:");
    for (const f of e.failures) p(`- run ${f.run}, case ${f.id} (${f.note}): expected ${f.expected}, got ${f.got}`);
  }
  p();

  const st = i.stress;
  p("### Guard stress test (independent of any model)");
  p();
  p(`Deliberately bad model output built from the synthetic fixture passages is fed to the citation guard: **${st.dropped} of ${st.total} bad sentences dropped (${pct(st.dropped / st.total)})**.`);
  p();
  p("| Fault type | Injected | Dropped |");
  p("|---|---|---|");
  for (const f of st.byFault) p(`| ${f.fault} | ${f.total} | ${f.dropped} |`);
  if (st.falseAccepts.length) {
    p();
    p("**False accepts (bad sentences the guard let through):**");
    for (const c of st.falseAccepts) p(`- (${c.fault}) "${c.text}"`);
    p();
    p(`The guard is lexical (content-word overlap with the cited passage, threshold ${pct(MIN_OVERLAP, 0)}): it reliably removes uncited, wrongly cited and invented sentences, but a **small addition to an otherwise supported sentence can still pass**. Mitigations in the product: the prompt asks for wording close to the source, every sentence has a chip that opens the verbatim source, and fewer than 2 surviving sentences falls back to the verbatim text. A stronger check (entailment model or LLM judge) is future work.`);
  }
  p();

  p("## Real content readiness");
  p();
  p("Verified passages available to learners today:");
  p();
  p("| Concept | Verified passages |");
  p("|---|---|");
  for (const c of i.coverage) p(`| ${c.id} | ${c.verified} |`);
  p();
  p(i.coverage.every((c) => c.verified === 0) ? "**No concept has verified content yet**: the explainer, practice items and the router's `answerable` flag cannot be evaluated on real content until Mohammed's verified passages are added." : "Evaluate the explainer on real content by pointing the harness at it once all concepts have verified passages.");
  p();
  p("## Reproduce");
  p();
  p("```");
  p("npm install");
  p("npm run eval            # router x3, explainer x3, writes EVAL.md and eval/results/latest.json");
  p("npm run eval -- --runs 5");
  p("```");
  p();
  p("To evaluate a real model set `LLM_PROVIDER`, `LLM_API_KEY`, `LLM_MODEL` (and optionally `LLM_API_STYLE`, `LLM_PRICE_IN_PER_MTOK`, `LLM_PRICE_OUT_PER_MTOK`) and, for embeddings, `EMBEDDING_PROVIDER`, `EMBEDDING_API_KEY`. Without them the mock adapters are used and this file says so at the top.");
  p();
  return L.join("\n");
}
